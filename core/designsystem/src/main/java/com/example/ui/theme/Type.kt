/**
 * Applies OpenType tabular numerals ("tnum") so live counters, vitals, charts,
 * and progress percentages maintain fixed character widths without horizontal layout jitter.
 */
fun TextStyle.tabular(): TextStyle = copy(fontFeatureSettings = "tnum")

